/**
 * ants.bench.probe.js — the ant painter's node microbenchmark: RASTERISER-PLAN §8.6 row 16, on
 * SYNTHETIC geometry at F39's own recorded density. Not a test: it prints tables and asserts
 * nothing about time. Its numbers go into §8.6 with the machine they were taken on.
 *
 * Run (the suite skips *.probe.js):
 *   npx react-scripts test --watchAll=false --testMatch "**\/ants.bench.probe.js"
 *
 * It measures in a plain node CHILD process on an esbuild bundle of the shipped painter, as
 * stage 1's and stage 2's probes do: jest's transform costs a hot pixel loop several times what
 * the bundle costs, and the design's own figures (§0's table) were taken that way, so this is
 * the only shape in which the two are comparable.
 *
 * The fixture is F39's two measured cameras (`docs/OPEN-FLAGS.md` F39): the report camera,
 * 4,756 runs and 72,554 CSS px of ants on a 1504 × 812 screen at dpr 1.5, and 4× in, 5,029 runs
 * and 275,820 CSS px. Three geometries at each: all-line runs (tile pieces and polygon fills,
 * the floor), arc runs at 40 px of screen radius, and arc runs at 8 px (a dense selection of
 * small curved marks, the ceiling).
 *
 * The first six cases build every run `closed: false`, so a SEVENTH repeats the report camera's
 * R = 8 case with every run CLOSED: that is the shape `loopRuns` returns for every loop with no
 * tile cut (`antRuns.js:83`), and it is the only case in which the seam join of D140 runs at all.
 */

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const f = (x, n = 2) => (x == null || !isFinite(x) ? "—" : x.toFixed(n));
function table(rows) {
    const keys = Object.keys(rows[0]);
    const w = keys.map((k) => Math.max(k.length, ...rows.map((r) => String(r[k]).length)));
    const line = (cells) => "  " + cells.map((c, i) => String(c).padStart(w[i])).join("  ");
    console.log(line(keys));
    console.log("  " + w.map((n) => "-".repeat(n)).join("  "));
    for (const r of rows) console.log(line(keys.map((k) => r[k])));
}

/** The shipped painter, bundled into the OS temp directory so a child node process can require it. */
function bundlePainter(minify) {
    const dir = path.join(os.tmpdir(), "boundless-ants-bench");
    fs.mkdirSync(dir, { recursive: true });
    const out = path.join(dir, minify ? "antPaint.min.cjs" : "antPaint.cjs");
    const esbuild = path.join(process.cwd(), "node_modules", ".bin", process.platform === "win32" ? "esbuild.cmd" : "esbuild");
    const args = [path.join("src", "engine", "raster", "antPaint.js"), "--bundle", "--format=cjs", "--target=es2019", "--outfile=" + out];
    if (minify) args.push("--minify");
    execFileSync(esbuild, args, { cwd: process.cwd(), stdio: "pipe" });
    return { dir, out };
}

const DRIVER_SRC = `
// generated by src/engine/raster/ants.bench.probe.js — §8.6 row 16
const ap = require(__BUNDLE__);
const { OverlayBuffer, paintPhase, ANT_PHASES } = ap;

const W = 2256, H = 1218, DPR = 1.5;        // Kobin's Chrome, 1504 × 812 CSS at dpr 1.5 (F39)
let seed = 20260916;
const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;

/** One run of arc pieces of screen radius R, chained around a circle, totalling \`len\` device px. */
function arcRun(cx, cy, R, len, closed) {
    const pieces = [];
    let a = rnd() * 6.283185307179586, left = len / R;         // radians still to place
    const pt = (th) => [cx + R * Math.cos(th), cy + R * Math.sin(th)];
    while (left > 1e-9) {
        const sw = Math.min(left, Math.PI / 2);
        pieces.push({ A: pt(a), B: pt(a + sw), C: [cx, cy], r: R, a0: a, sweep: sw });
        a += sw; left -= sw;
    }
    return { pieces, closed: !!closed, len };
}
function lineRun(cx, cy, len, closed) {
    const th = rnd() * 6.283185307179586;
    return { pieces: [{ line: true, A: [cx, cy], B: [cx + Math.cos(th) * len, cy + Math.sin(th) * len] }], closed: !!closed, len };
}
/**
 * A decision of \`n\` runs totalling \`cssPx\` CSS px of ants, scattered over the screen.
 * \`closed\` is what puts the seam join (D140) into the measurement: a closed run's first and last
 * lit stretches are the two halves of one dash, so the phase computes one \`joinExt\` per wrapped
 * run from two chords it builds.
 */
function decOf(n, cssPx, R, closed) {
    const runs = [], len = (cssPx * DPR) / n;
    for (let i = 0; i < n; i++) {
        const cx = rnd() * W, cy = rnd() * H;
        runs.push(R ? arcRun(cx, cy, R, len, closed) : lineRun(cx, cy, len, closed));
    }
    return { runs, marks: [], inkPx: 100 };
}

const now = () => Number(process.hrtime.bigint()) / 1e6;
const cases = [
    { name: "report camera, lines", n: 4756, css: 72554, R: 0 },
    { name: "report camera, arcs R = 40", n: 4756, css: 72554, R: 40 },
    { name: "report camera, arcs R = 8", n: 4756, css: 72554, R: 8 },
    { name: "4x in, lines", n: 5029, css: 275820, R: 0 },
    { name: "4x in, arcs R = 40", n: 5029, css: 275820, R: 40 },
    { name: "4x in, arcs R = 8", n: 5029, css: 275820, R: 8 },
    // The same geometry as row 3, every run CLOSED: the one case in which the seam join runs.
    { name: "report camera, closed loops R = 8", n: 4756, css: 72554, R: 8, closed: true },
];
const buf = new OverlayBuffer(W, H);
const view = { k: 1, tx: 0, ty: 0 }, css = { dpr: DPR };
const out = { node: process.version, W, H, dpr: DPR, bytes: buf.bytes, rows: [] };
for (const c of cases) {
    const dec = decOf(c.n, c.css, c.R, c.closed);
    let pieces = 0;
    for (const r of dec.runs) pieces += r.pieces.length;
    for (let i = 0; i < ANT_PHASES; i++) paintPhase(buf, dec, view, i, css);   // warm the JIT once
    const ms = [];
    let dashes = 0, stamps = 0, pixels = 0;
    for (let i = 0; i < 3 * ANT_PHASES; i++) {        // three passes of the eight phases
        const t = now();
        const s = paintPhase(buf, dec, view, i % ANT_PHASES, css);
        ms.push(now() - t);
        dashes += s.dashes; stamps += s.stamps; pixels += s.pixels;
    }
    const n = ms.length;
    ms.sort((a, b) => a - b);
    out.rows.push({ name: c.name, runs: c.n, pieces, cssPx: c.css,
        best: ms[0], mid: ms[n >> 1], worst: ms[n - 1],
        dashes: dashes / n, stamps: stamps / n, pixels: pixels / n });
}
// the clear, whole-plane and one 200-row band
{
    const d = buf.data;
    let full = Infinity, band = Infinity;
    for (let i = 0; i < 12; i++) {
        let t = now(); d.fill(0); let ms = now() - t; if (ms < full) full = ms;
        t = now(); d.fill(0, 500 * W * 4, 700 * W * 4); ms = now() - t; if (ms < band) band = ms;
    }
    out.clearFull = full; out.clearBand = band;
}
console.log(JSON.stringify(out));
`;

describe("§8.6 row 16 — the ant painter, one crawl phase at F39's two cameras", () => {
    test("measurement 16: ms, stamps, pixels written and µs a pixel", () => {
        const { dir, out: bundle } = bundlePainter(false);
        const driver = path.join(dir, "driver.js");
        fs.writeFileSync(driver, DRIVER_SRC.replace("__BUNDLE__", JSON.stringify(bundle)), "utf8");
        const json = execFileSync(process.execPath, [driver], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
        const r = JSON.parse(json);
        console.log("\n  §8.6 row 16 — one crawl phase, " + r.W + " × " + r.H + " device px at dpr " + r.dpr
            + ", node " + r.node + ", 24 phases after a warm-up pass; the counts are the mean over them");
        table(r.rows.map((e) => ({
            "": e.name,
            runs: e.runs, pieces: e.pieces, "CSS px": e.cssPx,
            dashes: Math.round(e.dashes), stamps: Math.round(e.stamps), "px written": Math.round(e.pixels),
            "% screen": f((100 * e.pixels) / (r.W * r.H), 1),
            "ms best": f(e.best), "ms median": f(e.mid), "ms worst": f(e.worst),
            "µs/px": f((1000 * e.mid) / e.pixels, 3),
            "µs/CSS px of ant": f((1000 * e.mid) / e.cssPx, 3),
        })));
        console.log("  the plane: " + (r.bytes / (1024 * 1024)).toFixed(2) + " MiB; the clear "
            + f(r.clearFull, 3) + " ms whole, " + f(r.clearBand, 3) + " ms over 200 rows (both inside the ms column)");
        console.log("  the bar (§10 stage 5c): 35 ms at the report camera, 140 ms at 4× in — what Chrome costs today is 50 / 200 ms (F39)");

        // N13's tree-shake claim, measured rather than argued
        const { out: min } = bundlePainter(true);
        const src = fs.readFileSync(min, "utf8");
        console.log("  the painter's own bundle: " + fs.statSync(min).size + " bytes minified; planArc in it: "
            + /planArc/.test(src) + "; chordCubic in it: " + /chordCubic/.test(src));
        expect(r.rows.length).toBe(7);
    }, 300000);
});

/**
 * overlay.bench.probe.js — the overlay layer's whole step: RASTERISER-PLAN §8.6 row 17
 * (§10 stage 5d, §15.3 "Stage 5d" Q7). Not a test: it prints tables and asserts nothing about
 * time. Its numbers go into §8.6 with the machine they were taken on.
 *
 * Run (the suite skips *.probe.js):
 *   npx react-scripts test --watchAll=false --testMatch "**\/overlay.bench.probe.js"
 *
 * **The blit's real cost is stage 7's.** There is no canvas in this tree — jsdom's `getContext`
 * returns null and node has none — so `putImageData` cannot be timed anywhere but Kobin's
 * Chrome. What is printed here is (a) the layer's own step with a RECORDING context, which is
 * the paint plus the layer's arithmetic and nothing of the compositor, and (b) a memcpy of the
 * same dirty bytes, which is the floor any real `putImageData` sits above. Neither is Chrome's
 * number.
 *
 * It measures in a plain node CHILD process on an esbuild bundle of the shipped layer, as rows
 * 15 and 16 do: jest's transform costs a hot pixel loop several times what the bundle costs, and
 * the design's own figures were taken that way, so this is the only shape in which the three are
 * comparable. The layer takes injected doubles for the canvas, the `ImageData`, the clock and
 * the timers, so no DOM is needed at all.
 *
 * The fixture is F39's report camera (`docs/OPEN-FLAGS.md` F39): 1504 × 812 CSS px at dpr 1.5,
 * 4,756 runs and 72,554 CSS px of ants, with 4,201 of the 8,509 pieces arcs — the density at
 * which F39 measured a 109 ms decision and a 50 ms frame.
 */

const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");

const f = (x, n = 2) => (x == null || !isFinite(x) ? "—" : x.toFixed(n));
function table(rows) {
    const keys = Object.keys(rows[0]);
    const w = keys.map((k) => Math.max(k.length, ...rows.map((r) => String(r[k]).length)));
    const line = (cells) => "  " + cells.map((c, i) => String(c).padStart(w[i])).join("  ");
    console.log(line(keys));
    console.log("  " + w.map((n) => "-".repeat(n)).join("  "));
    for (const r of rows) console.log(line(keys.map((k) => r[k])));
}

const DIR = path.join(os.tmpdir(), "boundless-overlay-bench");

/** One shipped module, bundled into the OS temp directory so a child node process can require it. */
function bundle(rel, name) {
    fs.mkdirSync(DIR, { recursive: true });
    const out = path.join(DIR, name);
    const esbuild = path.join(process.cwd(), "node_modules", ".bin", process.platform === "win32" ? "esbuild.cmd" : "esbuild");
    execFileSync(esbuild, [rel, "--bundle", "--format=cjs", "--target=es2019", "--outfile=" + out],
        { cwd: process.cwd(), stdio: "pipe" });
    return out;
}

const DRIVER_SRC = `
// generated by src/engine/raster/overlay.bench.probe.js — §8.6 row 17
const OverlayLayer = require(__LAYER__).default;
const { runPathData } = require(__RUNS__);

const CSS_W = 1504, CSS_H = 812, DPR = 1.5;      // F39's own screen
const W = Math.round(CSS_W * DPR), H = Math.round(CSS_H * DPR);
let seed = 20260921;
const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
const now = () => Number(process.hrtime.bigint()) / 1e6;

// ---- the doubles: a canvas with a recording context, an ImageData over the buffer's array ----
let blits = 0, blitBytes = 0;
function mkCanvas(w, h) {
    return {
        width: w, height: h, style: {},
        setAttribute() {},
        getContext: () => ({ putImageData(img, dx, dy, x0, y0, cw, ch) { blits++; blitBytes += cw * ch * 4; } }),
    };
}
const mkImageData = (data, w, h) => ({ data, width: w, height: h });
const host = { appendChild() {}, removeChild() {} };
let clock = 0;
const timers = { n: 0 };

function mkLayer() {
    return new OverlayLayer(host, {
        width: CSS_W, height: CSS_H, dpr: DPR,
        makeCanvas: mkCanvas, makeImageData: mkImageData,
        setTimer: () => ++timers.n, clearTimer: () => {},
        now: () => clock,
    });
}

// ---- F39's report camera, as geometry ----
/** One run of arc pieces of screen radius R, chained around a circle, totalling \`len\` device px. */
function arcRun(cx, cy, R, len) {
    const pieces = [];
    let a = rnd() * 6.283185307179586, left = len / R;
    const pt = (th) => [cx + R * Math.cos(th), cy + R * Math.sin(th)];
    while (left > 1e-9) {
        const sw = Math.min(left, Math.PI / 2);
        pieces.push({ A: pt(a), B: pt(a + sw), C: [cx, cy], r: R, a0: a, sweep: sw });
        a += sw; left -= sw;
    }
    return { pieces, closed: false, len };
}
/** A polyline run of \`segs\` segments, turning at each vertex, totalling \`len\` device px. */
function lineRun(cx, cy, len, segs) {
    const pieces = [];
    let th = rnd() * 6.283185307179586, x = cx, y = cy;
    for (let i = 0; i < segs; i++) {
        const L = len / segs, nx = x + Math.cos(th) * L, ny = y + Math.sin(th) * L;
        pieces.push({ line: true, A: [x, y], B: [nx, ny] });
        x = nx; y = ny; th += 0.6;
    }
    return { pieces, closed: false, len };
}
/**
 * F39's recorded density, piece for piece: 4,756 runs over 72,554 CSS px of ants, 8,509 pieces
 * of which 4,201 are arcs. A run carries 22.9 device px of ants, so an arc of screen radius 8
 * sweeps 2.86 rad and is cut into two chord pieces — 2,100 arc runs give 4,200 arc pieces, and
 * the 2,656 line runs carry 4,309 segments between them.
 */
function reportDec(key) {
    const N = 4756, CSS_PX = 72554, ARC_RUNS = 2100, TWO_SEG = 1653;
    const runs = [], len = (CSS_PX * DPR) / N;
    for (let i = 0; i < N; i++) {
        const cx = rnd() * W, cy = rnd() * H;
        runs.push(i < ARC_RUNS ? arcRun(cx, cy, 8, len) : lineRun(cx, cy, len, i - ARC_RUNS < TWO_SEG ? 2 : 1));
    }
    return { key, inkPx: 100, runs, marks: [], edges: [], off: null };
}
/** A few dozen straight screen-edge spans, the shape \`_selEdges\` returns (§15.3 Q3). */
function edgesOf(n) {
    const sides = ["left", "right", "top", "bottom"], out = [];
    for (let i = 0; i < n; i++) {
        const side = sides[i & 3], from = rnd() * 600;
        out.push({ side, from, to: from + 40 + rnd() * 160, chevron: false });
    }
    return out;
}

const view = (over) => Object.assign({ rev: 1, mode: "plates", q: 0, Zq: 1, Z: 1, s: 1,
    ox: 0, oy: 0, dx: 0, dy: 0, dpr: DPR, cssW: CSS_W, cssH: CSS_H, k: 1, tx: 0, ty: 0 }, over);

function stat(ms) {
    const a = ms.slice().sort((x, y) => x - y);
    return { best: a[0], mid: a[a.length >> 1], worst: a[a.length - 1] };
}

const out = { node: process.version, W, H, dpr: DPR, rows: [], decide: [] };
const dec = reportDec("d0");
out.runs = dec.runs.length;
out.pieces = dec.runs.reduce((n, r) => n + r.pieces.length, 0);
out.arcPieces = dec.runs.reduce((n, r) => n + (r.pieces[0].line ? 0 : r.pieces.length), 0);

// ---- 1. the whole step, three shapes ----
{
    const layer = mkLayer();
    layer.show(dec, view());                       // the first paint: allocate and warm the JIT
    layer.resume();
    for (let i = 0; i < 8; i++) layer.step();

    // (a) a crawl tick: one phase into the plane plus one blit
    let ms = [];
    for (let i = 0; i < 24; i++) { const t = now(); layer.step(); ms.push(now() - t); }
    const rep = layer.report();
    out.rows.push(Object.assign({ name: "crawl tick (paint + blit)" }, stat(ms),
        { dashes: rep.dashes, stamps: rep.stamps, pixels: rep.pixels, blitPx: rep.blitPx }));

    // (b) a camera step at the same quantum: the delta transform and nothing else
    ms = [];
    for (let i = 0; i < 24; i++) {
        const t = now();
        layer.show(dec, view({ k: 1 + i / 1000, tx: i, ty: -i }));
        ms.push(now() - t);
    }
    out.rows.push(Object.assign({ name: "camera step (transform only)" }, stat(ms),
        { dashes: 0, stamps: 0, pixels: 0, blitPx: 0 }));

    // (c) a quantum change: a full repaint in the same turn
    ms = [];
    for (let i = 0; i < 24; i++) {
        const t = now();
        layer.show(dec, view({ q: i + 1, Zq: 1 + i / 100, k: 1 + i / 100 }));
        ms.push(now() - t);
    }
    const rep2 = layer.report();
    out.rows.push(Object.assign({ name: "quantum change (repaint + blit)" }, stat(ms),
        { dashes: rep2.dashes, stamps: rep2.stamps, pixels: rep2.pixels, blitPx: rep2.blitPx }));

    // (d) the four edge strips, 48 spans, at the same phase as the body (§15.3 Q3)
    const decE = reportDec("d1");
    decE.edges = edgesOf(48);
    layer.show(decE, view({ q: 99 }));
    ms = [];
    for (let i = 0; i < 24; i++) {
        const t = now();
        layer._paintEdges(decE, null);
        ms.push(now() - t);
    }
    out.rows.push(Object.assign({ name: "the four edge strips, 48 spans" }, stat(ms),
        { dashes: layer.report().edgeDashes, stamps: 0, pixels: 0, blitPx: 0 }));

    out.bytes = layer.report().bytes;
    out.stripBytes = layer.report().stripBytes;
    out.blits = blits;
}

// ---- 2. the blit's floor: a memcpy of the same bytes ----
{
    const src = new Uint8ClampedArray(W * H * 4), dst = new Uint8ClampedArray(W * H * 4);
    const band = 200 * W * 4;                       // the dirty rect of a typical phase
    let full = Infinity, part = Infinity;
    for (let i = 0; i < 12; i++) {
        let t = now(); dst.set(src); let d = now() - t; if (d < full) full = d;
        t = now(); dst.set(src.subarray(0, band), 0); d = now() - t; if (d < part) part = d;
    }
    out.copyFull = full; out.copyBand = part;
}

// ---- 3. the per-decision cost with and without the \`d\` build ----
{
    const O = { x: 1234.5, y: -987.25 }, sc = 1.25;
    const loops = dec.runs.map((r) => r.pieces);
    for (let i = 0; i < 2; i++) for (const loop of loops) runPathData({ pieces: loop, closed: false }, O.x, O.y, sc);
    let ms = [], bytes = 0;
    for (let i = 0; i < 5; i++) {
        const t = now();
        let n = 0;
        for (const loop of loops) n += runPathData({ pieces: loop, closed: false }, O.x, O.y, sc).length;
        ms.push(now() - t); bytes = n;
    }
    out.decide.push(Object.assign({ name: "with the d build (SVG)" }, stat(ms), { bytes }));
    ms = [];
    for (let i = 0; i < 5; i++) {
        const t = now();
        const keep = [];
        for (const loop of loops) keep.push({ pieces: loop, closed: false });
        ms.push(now() - t);
        if (keep.length !== loops.length) throw new Error("lost a run");
    }
    out.decide.push(Object.assign({ name: "keeping the pieces (raster)" }, stat(ms), { bytes: 0 }));
}

console.log(JSON.stringify(out));
`;

describe("§8.6 row 17 — the overlay layer's whole step at F39's report camera", () => {
    test("measurement 17: the step, the strips, the blit's floor, and the decision with and without `d`", () => {
        const layer = bundle(path.join("src", "engine", "raster", "OverlayLayer.js"), "OverlayLayer.cjs");
        const runs = bundle(path.join("src", "engine", "geometry", "antRuns.js"), "antRuns.cjs");
        const driver = path.join(DIR, "driver.js");
        fs.writeFileSync(driver, DRIVER_SRC
            .replace("__LAYER__", JSON.stringify(layer))
            .replace("__RUNS__", JSON.stringify(runs)), "utf8");
        const json = execFileSync(process.execPath, [driver], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
        const r = JSON.parse(json);

        console.log("\n  §8.6 row 17 — " + r.W + " × " + r.H + " device px at dpr " + r.dpr + ", node " + r.node
            + "; F39's report camera: " + r.runs + " runs, " + r.pieces + " pieces (" + r.arcPieces + " arc), "
            + "24 measurements after a warm-up pass");
        table(r.rows.map((e) => ({
            "": e.name,
            "ms best": f(e.best), "ms median": f(e.mid), "ms worst": f(e.worst),
            dashes: e.dashes, stamps: e.stamps, "px written": e.pixels, "blit px": e.blitPx,
        })));
        console.log("  the plane " + (r.bytes / (1024 * 1024)).toFixed(2) + " MiB + the four strips "
            + (r.stripBytes / 1024).toFixed(0) + " KiB; " + r.blits + " blits, one per paint (FC4)");
        console.log("  the blit's FLOOR — a memcpy of the same bytes, not `putImageData`: "
            + f(r.copyFull, 3) + " ms whole plane, " + f(r.copyBand, 3) + " ms over a 200-row band. "
            + "What Chrome's `putImageData` costs over 2.75 Mpx is stage 7's, in a browser (§9.4).");
        console.log("\n  the decision, with and without the `d` build (the one additive fork in `overlays.js`):");
        table(r.decide.map((e) => ({
            "": e.name,
            "ms best": f(e.best, 3), "ms median": f(e.mid, 3), "ms worst": f(e.worst, 3),
            "KB of path data": f(e.bytes / 1024, 1),
        })));

        expect(r.rows.length).toBe(4);
        expect(r.decide.length).toBe(2);
    }, 300000);
});
